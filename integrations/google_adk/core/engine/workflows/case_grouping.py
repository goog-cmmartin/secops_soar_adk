"""
High-Signal Entity Case Grouping & Merging Workflow for Google SecOps SOAR.

Scans open SOAR cases within a configurable lookback and grouping timeframe (e.g. 24h),
extracts high-signal alert entities (filtering out generic OS accounts, system binaries,
placeholder hashes, and post-ingestion enrichment noise), enforces multi-host magnet
guardrails, and groups/merges related cases via POST /v1beta/{parent}/cases:merge.
"""

from __future__ import annotations

from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
import ipaddress
import json
from typing import TYPE_CHECKING, Any, Dict, List, Optional, Set, Tuple, Union

if TYPE_CHECKING:
    from adapters.google_secops import GoogleSecOpsAdapter

from engine.domain import UniversalDictMixin
from engine.parsing import parse_timestamp
from engine.workflows.correlate_silent_detections import (
    GENERIC_BINARIES,
    GENERIC_BINARY_PATH_SUBSTRINGS,
    GENERIC_METADATA_VALUES,
    GENERIC_USERS,
    KNOWN_GENERIC_BINARY_HASHES,
    _HOSTNAME_TYPE_TOKENS,
    _USER_TYPE_TOKENS,
    _clean_case_id,
    is_noisy_entity,
    is_noisy_ip,
)

# Synthetic SHA-256 tail commonly generated by LLMs when mutating the empty-file SHA-256 hash
_SYNTHETIC_EMPTY_HASH_TAIL = "98fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b8"

_IP_TYPE_TOKENS = {
    "IP",
    "ADDRESS",
    "SOURCEADDRESS",
    "DESTINATIONADDRESS",
    "SOURCEIP",
    "DESTINATIONIP",
    "SRCIP",
    "DSTIP",
}

_HASH_TYPE_TOKENS = {
    "FILEHASH",
    "HASH",
    "SHA256",
    "MD5",
    "SHA1",
    "PARENTHASH",
    "CHILDHASH",
}

_EXCLUDED_GROUPING_TYPES = {
    "DESTINATIONURL",
    "URL",
    "GENERIC",
    "GENERICENTITY",
    "THREATSIGNATURE",
    "FILENAME",
    "PROCESS",
    "SOURCEPROCESSNAME",
    "DESTINATIONPROCESSNAME",
    "PARENTPROCESS",
    "CHILDPROCESS",
    "OUTCOME",
    "UNKNOWN",
    "EMAILSUBJECT",
}


def _is_ip_literal(val: str) -> bool:
    try:
        ipaddress.ip_address(val.strip())
        return True
    except ValueError:
        return False


def classify_high_signal_entity(
    raw_entity: Dict[str, Any],
    include_enriched_entities: bool = False,
) -> Optional[Tuple[str, str]]:
    """
    Evaluates a raw SOAR alert entity and returns (canonical_type, normalized_identifier)
    if and only if it qualifies as a high-signal cross-case correlation anchor.
    Returns None if the entity is noisy, generic, or excluded.
    """
    if not include_enriched_entities and raw_entity.get("manuallyCreated") is True:
        return None

    raw_type = str(raw_entity.get("type") or raw_entity.get("entityType") or "").strip().upper()
    type_norm = raw_type.replace("-", "").replace("_", "").replace(" ", "")
    ident = str(raw_entity.get("identifier") or "").strip()
    if not ident or len(ident) < 2:
        return None

    ident_low = ident.lower()
    ident_up = ident.upper()

    if raw_type in _EXCLUDED_GROUPING_TYPES or type_norm in _EXCLUDED_GROUPING_TYPES:
        return None

    if ident_low in GENERIC_METADATA_VALUES or ident_low in GENERIC_USERS:
        return None

    if any(
        ident_low == b or ident_low.endswith("/" + b) or ident_low.endswith("\\" + b)
        for b in GENERIC_BINARIES
    ) or any(sub in ident_low for sub in GENERIC_BINARY_PATH_SUBSTRINGS):
        return None

    if ident_low in KNOWN_GENERIC_BINARY_HASHES or _SYNTHETIC_EMPTY_HASH_TAIL in ident_low:
        return None

    # 1. Hostname entities
    if raw_type in _HOSTNAME_TYPE_TOKENS or type_norm in _HOSTNAME_TYPE_TOKENS:
        # Allow cloud instance display names with spaces (e.g. "BACKSTAGE - IDANSKI") if not generic metadata
        probe_val = ident_low.replace(" ", "_")
        if is_noisy_entity(probe_val, "HOSTNAME"):
            return None
        if _is_ip_literal(ident):
            return None if is_noisy_ip(ident) else ("IP", ident_up)
        return ("HOSTNAME", ident_up)

    # 2. IP / Address entities
    if raw_type in _IP_TYPE_TOKENS or type_norm in _IP_TYPE_TOKENS or _is_ip_literal(ident):
        if is_noisy_ip(ident):
            return None
        return ("IP", ident_up)

    # 3. User / IAM Role entities
    if raw_type in _USER_TYPE_TOKENS or type_norm in _USER_TYPE_TOKENS:
        # Do not double-count IP literals mapped into USERUNIQNAME by vendor connectors
        if _is_ip_literal(ident):
            return None if is_noisy_ip(ident) else ("IP", ident_up)
        if is_noisy_entity(ident, "USERUNIQNAME"):
            return None
        return ("USER", ident_up)

    # 4. FileHash entities
    if raw_type in _HASH_TYPE_TOKENS or type_norm in _HASH_TYPE_TOKENS:
        if is_noisy_entity(ident, "FILEHASH"):
            return None
        return ("FILEHASH", ident_up)

    return None


@dataclass
class CaseGroupingResult(UniversalDictMixin):
    """Structured result for the High-Signal Case Grouping & Merging workflow."""

    dry_run: bool = True
    environment_filter: List[str] = field(default_factory=list)
    lookback_hours: int = 24
    grouping_window_hours: int = 24
    min_shared_entities: int = 1
    max_distinct_hosts_per_case: int = 1
    min_case_age_minutes: int = 5
    scanned_cases_count: int = 0
    eligible_cases_count: int = 0
    skipped_multi_host_cases: List[Dict[str, Any]] = field(default_factory=list)
    skipped_settling_cases: List[Dict[str, Any]] = field(default_factory=list)
    overlap_pairs_count: int = 0
    overlap_pairs: List[Dict[str, Any]] = field(default_factory=list)
    merge_clusters_count: int = 0
    merge_clusters: List[Dict[str, Any]] = field(default_factory=list)
    merge_executions: List[Dict[str, Any]] = field(default_factory=list)
    case_entity_inventory: List[Dict[str, Any]] = field(default_factory=list)
    summary_markdown: str = ""


class GroupCasesByEntityWorkflow:
    """Discovers and merges open SOAR cases sharing high-signal alert entities."""

    def __init__(self, adapter: Optional["GoogleSecOpsAdapter"] = None):
        if adapter is None:
            from adapters.google_secops import GoogleSecOpsAdapter

            adapter = GoogleSecOpsAdapter()
        self.adapter = adapter

    def _fetch_single_case_profile(
        self,
        case_obj: Dict[str, Any],
        include_enriched_entities: bool = False,
        profile_cache: Optional[Dict[str, Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        case_name = str(case_obj.get("name") or "")
        cid = _clean_case_id(case_name or case_obj.get("id") or "")
        # Only call get_case if basic metadata (createTime) is absent (list_cases already includes it)
        if not case_obj.get("createTime"):
            try:
                case_obj = self.adapter.get_case(cid)
            except Exception:
                pass

        create_ms = int(case_obj.get("createTime") or 0)
        update_ms = int(case_obj.get("updateTime") or create_ms or 0)
        alert_cnt_hint = int(case_obj.get("alertCount") or 0)
        cache_key = f"{cid}:{update_ms}:{alert_cnt_hint}:{int(bool(include_enriched_entities))}"

        if isinstance(profile_cache, dict) and cache_key in profile_cache:
            cached = dict(profile_cache[cache_key])
            ents_dict = cached.get("entities") or {}
            cached["entities_set"] = {k: set(v) for k, v in ents_dict.items()}
            return cached

        high_signal_by_type: Dict[str, Set[str]] = defaultdict(set)
        alert_summaries: List[Dict[str, Any]] = []
        distinct_alert_ids: Set[str] = set()

        # Fetch all involved entities across all alerts of the case in 1 API call (cases/{cid}/caseAlerts/-/involvedEntities)
        used_wildcard = False
        if hasattr(self.adapter, "list_case_entities"):
            try:
                raw_ents = self.adapter.list_case_entities(cid)
                if isinstance(raw_ents, list):
                    used_wildcard = True
                    for ent in raw_ents:
                        aid = str(ent.get("alertIdentifier") or "").strip()
                        if aid and aid not in distinct_alert_ids:
                            distinct_alert_ids.add(aid)
                            alert_summaries.append(
                                {
                                    "alert_id": aid,
                                    "display_name": aid,
                                    "product": "",
                                    "rule_generator": "",
                                    "create_time": None,
                                }
                            )
                        classified = classify_high_signal_entity(
                            ent, include_enriched_entities=include_enriched_entities
                        )
                        if classified is not None:
                            etype, norm_val = classified
                            high_signal_by_type[etype].add(norm_val)
            except Exception:
                used_wildcard = False

        if not used_wildcard:
            alerts = []
            try:
                alerts = self.adapter.list_case_alerts(cid)
            except Exception:
                alerts = []
            for a in alerts:
                aname = str(a.get("name") or "")
                aid = aname.split("/")[-1] if "/" in aname else str(a.get("id") or "")
                alert_summaries.append(
                    {
                        "alert_id": aid,
                        "display_name": a.get("displayName") or a.get("ruleGenerator") or "",
                        "product": a.get("product") or a.get("vendor") or "",
                        "rule_generator": a.get("ruleGenerator") or "",
                        "create_time": a.get("createTime"),
                    }
                )
                try:
                    raw_ents = self.adapter.list_alert_entities(aname)
                    for ent in raw_ents:
                        classified = classify_high_signal_entity(
                            ent, include_enriched_entities=include_enriched_entities
                        )
                        if classified is not None:
                            etype, norm_val = classified
                            high_signal_by_type[etype].add(norm_val)
                except Exception:
                    pass

        tags_list = [
            str(t.get("displayName") or t.get("tag") or "").strip()
            for t in (case_obj.get("tags") or [])
            if isinstance(t, dict) and (t.get("displayName") or t.get("tag"))
        ]
        create_dt = (
            datetime.fromtimestamp(create_ms / 1000.0, tz=timezone.utc)
            if create_ms > 0
            else None
        )
        effective_alert_count = alert_cnt_hint or len(alert_summaries) or 1

        profile_out = {
            "case_id": cid,
            "display_name": case_obj.get("displayName") or f"Case {cid}",
            "environment": case_obj.get("environment") or "Default Environment",
            "status": case_obj.get("status") or "OPENED",
            "stage": case_obj.get("stage") or "Triage",
            "priority": case_obj.get("priority") or "PRIORITY_MEDIUM",
            "incident": bool(case_obj.get("incident")),
            "type": case_obj.get("type") or "EXTERNAL",
            "create_time_ms": create_ms,
            "update_time_ms": update_ms,
            "create_time_iso": create_dt.strftime("%Y-%m-%dT%H:%M:%SZ") if create_dt else None,
            "alert_count": effective_alert_count,
            "alerts": alert_summaries,
            "tags": tags_list,
            "entities": {k: sorted(list(v)) for k, v in high_signal_by_type.items()},
        }
        if isinstance(profile_cache, dict):
            profile_cache[cache_key] = dict(profile_out)

        profile_with_set = dict(profile_out)
        profile_with_set["entities_set"] = high_signal_by_type
        return profile_with_set

    def execute(
        self,
        environments: Optional[List[str]] = None,
        lookback_hours: int = 24,
        grouping_window_hours: int = 24,
        min_shared_entities: int = 1,
        max_cases: int = 100,
        max_distinct_hosts_per_case: int = 1,
        min_case_age_minutes: int = 5,
        include_enriched_entities: bool = False,
        require_shared_host_when_both_have_hosts: bool = True,
        dry_run: bool = True,
        post_wall_comment: bool = True,
        trigger_correlation_tag: bool = True,
        target_case_ids: Optional[List[Union[str, int]]] = None,
        profile_cache: Optional[Dict[str, Dict[str, Any]]] = None,
    ) -> CaseGroupingResult:
        """
        Scans open SOAR cases, computes high-signal entity overlaps within grouping_window_hours,
        and either returns a dry-run merge plan or executes cases:merge.
        """
        lookback_hours = max(1, int(lookback_hours or 24))
        grouping_window_hours = max(1, int(grouping_window_hours or 24))
        min_shared_entities = max(1, int(min_shared_entities or 1))
        max_cases = max(1, min(500, int(max_cases or 100)))
        max_distinct_hosts_per_case = max(1, int(max_distinct_hosts_per_case or 1))
        min_case_age_minutes = max(0, int(min_case_age_minutes if min_case_age_minutes is not None else 5))

        env_filter_clean = [
            e.strip() for e in (environments or []) if e and str(e).strip()
        ]
        env_filter_lower = {e.lower() for e in env_filter_clean}

        # 1. Fetch candidate open cases
        raw_cases: List[Dict[str, Any]] = []
        if target_case_ids:
            for tid in target_case_ids:
                clean_tid = _clean_case_id(tid)
                if clean_tid:
                    try:
                        c_obj = self.adapter.get_case(clean_tid)
                        raw_cases.append(c_obj)
                    except Exception:
                        pass
        else:
            now_utc = datetime.now(timezone.utc)
            cutoff_ms = int((now_utc - timedelta(hours=lookback_hours)).timestamp() * 1000)
            res = self.adapter.list_cases(
                filter='status = "OPENED"',
                page_size=min(max_cases, 200),
                order_by="createTime desc",
            )
            fetched = res.get("cases", []) if isinstance(res, dict) else []
            for c_obj in fetched:
                if c_obj.get("status") and str(c_obj.get("status")).upper() != "OPENED":
                    continue
                c_env = str(c_obj.get("environment") or "").strip()
                if env_filter_lower and c_env.lower() not in env_filter_lower:
                    continue
                c_ms = int(c_obj.get("createTime") or 0)
                if c_ms > 0 and c_ms < cutoff_ms:
                    continue
                raw_cases.append(c_obj)
                if len(raw_cases) >= max_cases:
                    break

        # 2. Extract high-signal entity profiles (with cache support and low concurrency to respect 100/min quota)
        profiles: List[Dict[str, Any]] = []
        if raw_cases:
            workers = min(2, len(raw_cases))
            with ThreadPoolExecutor(max_workers=workers) as executor:
                futs = {
                    executor.submit(
                        self._fetch_single_case_profile,
                        c_obj,
                        include_enriched_entities,
                        profile_cache,
                    ): c_obj
                    for c_obj in raw_cases
                }
                for fut in as_completed(futs):
                    try:
                        prof = fut.result()
                        if env_filter_lower and prof["environment"].lower() not in env_filter_lower:
                            continue
                        if prof["status"].upper() != "OPENED":
                            continue
                        profiles.append(prof)
                    except Exception:
                        pass

        # Sort chronologically ascending (oldest first)
        profiles.sort(key=lambda p: (p["create_time_ms"], int(p["case_id"]) if str(p["case_id"]).isdigit() else 0))

        # 3. Apply Multi-Host Magnet Guardrail & Settle Window / Active Playbook Tag Guardrail
        eligible_profiles: List[Dict[str, Any]] = []
        skipped_multi_host: List[Dict[str, Any]] = []
        skipped_settling: List[Dict[str, Any]] = []
        now_ms = int(datetime.now(timezone.utc).timestamp() * 1000)
        min_age_ms = min_case_age_minutes * 60000
        active_trigger_tags = {"Run_Case_Correlation", "Tune:Candidate", "Tune:Approve"}

        for prof in profiles:
            hosts = prof["entities"].get("HOSTNAME", [])
            case_tags_set = set(prof.get("tags") or [])
            age_ms = (now_ms - prof["create_time_ms"]) if prof.get("create_time_ms", 0) > 0 else min_age_ms
            if not target_case_ids and min_age_ms > 0 and age_ms < min_age_ms:
                skipped_settling.append(
                    {
                        "case_id": prof["case_id"],
                        "display_name": prof["display_name"],
                        "create_time_iso": prof.get("create_time_iso"),
                        "age_minutes": round(age_ms / 60000.0, 1),
                        "reason": (
                            f"Case age ({round(age_ms / 60000.0, 1)}m) is within the {min_case_age_minutes}m "
                            "T+0m playbook settle window; deferred to next grouping cycle."
                        ),
                    }
                )
                continue
            if not target_case_ids and case_tags_set.intersection(active_trigger_tags):
                skipped_settling.append(
                    {
                        "case_id": prof["case_id"],
                        "display_name": prof["display_name"],
                        "create_time_iso": prof.get("create_time_iso"),
                        "active_tags": sorted(list(case_tags_set.intersection(active_trigger_tags))),
                        "reason": "Case currently carries active reaction trigger tag(s); deferred until in-flight playbooks complete.",
                    }
                )
                continue
            if len(hosts) > max_distinct_hosts_per_case:
                skipped_multi_host.append(
                    {
                        "case_id": prof["case_id"],
                        "display_name": prof["display_name"],
                        "environment": prof["environment"],
                        "alert_count": prof["alert_count"],
                        "distinct_hostnames_count": len(hosts),
                        "hostnames": hosts,
                        "reason": (
                            f"Case contains {len(hosts)} distinct hostnames (> max_distinct_hosts_per_case="
                            f"{max_distinct_hosts_per_case}); excluded from transitive clustering to prevent "
                            "cross-host magnet bridging."
                        ),
                    }
                )
            else:
                eligible_profiles.append(prof)

        # 4. Compute pairwise high-signal overlaps within grouping_window_hours
        window_ms = grouping_window_hours * 3600 * 1000
        overlap_pairs: List[Dict[str, Any]] = []
        adj_pairs: List[Tuple[str, str]] = []
        prof_by_id = {p["case_id"]: p for p in eligible_profiles}

        for i in range(len(eligible_profiles)):
            p1 = eligible_profiles[i]
            cid1 = p1["case_id"]
            for j in range(i + 1, len(eligible_profiles)):
                p2 = eligible_profiles[j]
                cid2 = p2["case_id"]

                # Must match environment and case type (Chronicle SOAR forbids merging TEST with EXTERNAL)
                if p1["environment"].lower() != p2["environment"].lower():
                    continue
                if (p1["type"] == "TEST") != (p2["type"] == "TEST"):
                    continue

                # Enforce grouping_window_hours
                if p1["create_time_ms"] > 0 and p2["create_time_ms"] > 0:
                    if abs(p2["create_time_ms"] - p1["create_time_ms"]) > window_ms:
                        continue

                # If both cases have HOSTNAME entities and require_shared_host_when_both_have_hosts is True,
                # prevent merging two cases that belong to completely disjoint hosts
                hosts1 = p1["entities_set"].get("HOSTNAME", set())
                hosts2 = p2["entities_set"].get("HOSTNAME", set())
                if require_shared_host_when_both_have_hosts and hosts1 and hosts2:
                    if not hosts1.intersection(hosts2):
                        continue

                shared_by_type: Dict[str, List[str]] = {}
                for etype, vals1 in p1["entities_set"].items():
                    vals2 = p2["entities_set"].get(etype, set())
                    common = vals1.intersection(vals2)
                    if common:
                        shared_by_type[etype] = sorted(list(common))

                total_shared = sum(len(v) for v in shared_by_type.values())
                if total_shared >= min_shared_entities:
                    time_diff_min = round(
                        abs(p2["create_time_ms"] - p1["create_time_ms"]) / 60000.0, 1
                    )
                    overlap_pairs.append(
                        {
                            "case_1": cid1,
                            "case_2": cid2,
                            "case_1_title": p1["display_name"],
                            "case_2_title": p2["display_name"],
                            "environment": p1["environment"],
                            "time_delta_minutes": time_diff_min,
                            "shared_count": total_shared,
                            "shared_entities": shared_by_type,
                        }
                    )
                    adj_pairs.append((cid1, cid2))

        # 5. Build connected components (Union-Find) while enforcing host compatibility across the cluster
        parent: Dict[str, str] = {p["case_id"]: p["case_id"] for p in eligible_profiles}
        cluster_hosts: Dict[str, Set[str]] = {
            p["case_id"]: set(p["entities_set"].get("HOSTNAME", set()))
            for p in eligible_profiles
        }

        def find(item: str) -> str:
            if parent[item] != item:
                parent[item] = find(parent[item])
            return parent[item]

        for cid1, cid2 in adj_pairs:
            r1 = find(cid1)
            r2 = find(cid2)
            if r1 == r2:
                continue
            h1 = cluster_hosts.get(r1, set())
            h2 = cluster_hosts.get(r2, set())
            if require_shared_host_when_both_have_hosts and h1 and h2 and not h1.intersection(h2):
                continue
            combined_hosts = h1.union(h2)
            if len(combined_hosts) > max_distinct_hosts_per_case:
                continue
            parent[r2] = r1
            cluster_hosts[r1] = combined_hosts

        clusters_map: Dict[str, List[str]] = defaultdict(list)
        for p in eligible_profiles:
            cid = p["case_id"]
            clusters_map[find(cid)].append(cid)

        # 6. Rank and select target_case_id for each multi-case cluster
        merge_clusters: List[Dict[str, Any]] = []
        for members in clusters_map.values():
            if len(members) < 2:
                continue

            # Target case selection heuristic:
            # Prefer primary cloud/CSPM/EDR alert cases over secondary correlation/replay rule cases,
            # then Incident-stage cases, then oldest create_time_ms
            def _target_sort_key(cid: str):
                pr = prof_by_id[cid]
                dname_low = pr["display_name"].lower()
                is_secondary_rule = any(
                    tok in dname_low for tok in ("sshpass interactive", "impossible travel")
                )
                has_wiz = (
                    "Wiz" in pr["tags"]
                    or any("wiz" in str(a.get("product") or "").lower() for a in pr["alerts"])
                    or any(tok in dname_low for tok in ("recon:", "unauthorizedaccess:", "unusual mass"))
                )
                is_inc = pr["incident"] or pr["stage"].lower() == "incident"
                return (
                    1 if is_secondary_rule else 0,
                    0 if has_wiz else 1,
                    0 if is_inc else 1,
                    pr["create_time_ms"] if pr["create_time_ms"] > 0 else float("inf"),
                    int(cid) if str(cid).isdigit() else 0,
                )

            ranked = sorted(members, key=_target_sort_key)
            target_cid = ranked[0]
            raw_source_cids = [c for c in members if c != target_cid]
            source_cids: List[str] = []
            for sc in raw_source_cids:
                # Live pre-merge check: ensure child case does not currently carry Run_Case_Correlation / Tune:* trigger tags
                try:
                    live_sc = self.adapter.get_case(sc, expand="tags")
                    live_tags = {
                        str(t.get("displayName") or t.get("tag") or "").strip()
                        for t in (live_sc.get("tags") or [])
                        if isinstance(t, dict) and (t.get("displayName") or t.get("tag"))
                    }
                    if live_tags.intersection(active_trigger_tags):
                        skipped_settling.append(
                            {
                                "case_id": sc,
                                "display_name": prof_by_id[sc]["display_name"],
                                "create_time_iso": prof_by_id[sc].get("create_time_iso"),
                                "active_tags": sorted(list(live_tags.intersection(active_trigger_tags))),
                                "reason": "Child case currently has active reaction trigger tag(s); deferred merge to prevent dissolving in-flight playbook.",
                            }
                        )
                        continue
                except Exception:
                    pass
                source_cids.append(sc)

            if not source_cids:
                continue

            # Aggregate shared entities across cluster
            cluster_shared: Dict[str, Set[str]] = defaultdict(set)
            for op in overlap_pairs:
                if op["case_1"] in members and op["case_2"] in members:
                    for et, vals in op["shared_entities"].items():
                        cluster_shared[et].update(vals)

            merge_clusters.append(
                {
                    "target_case_id": target_cid,
                    "target_case_title": prof_by_id[target_cid]["display_name"],
                    "target_case_stage": prof_by_id[target_cid]["stage"],
                    "environment": prof_by_id[target_cid]["environment"],
                    "source_case_ids": source_cids,
                    "source_cases": [
                        {
                            "case_id": sc,
                            "display_name": prof_by_id[sc]["display_name"],
                            "create_time_iso": prof_by_id[sc]["create_time_iso"],
                            "alert_count": prof_by_id[sc]["alert_count"],
                        }
                        for sc in source_cids
                    ],
                    "all_case_ids": [target_cid] + source_cids,
                    "shared_entities": {k: sorted(list(v)) for k, v in cluster_shared.items()},
                }
            )

        # 7. Execute merges if dry_run is False
        merge_executions: List[Dict[str, Any]] = []
        if not dry_run and merge_clusters:
            for cl in merge_clusters:
                target_cid = cl["target_case_id"]
                source_cids = cl["source_case_ids"]
                all_cids = cl["all_case_ids"]
                exec_record: Dict[str, Any] = {
                    "target_case_id": target_cid,
                    "source_case_ids": source_cids,
                    "status": "PENDING",
                    "wall_comment_posted": False,
                    "correlation_tag_triggered": False,
                    "error": None,
                }
                try:
                    merge_res = self.adapter.merge_cases(
                        case_ids=all_cids,
                        target_case_id=target_cid,
                    )
                    exec_record["status"] = "MERGED"
                    exec_record["api_response"] = merge_res

                    if post_wall_comment:
                        comment_md = self._build_cluster_wall_comment(cl)
                        try:
                            self.adapter.create_case_comment(target_cid, comment_md)
                            exec_record["wall_comment_posted"] = True
                        except Exception:
                            pass

                    if trigger_correlation_tag:
                        try:
                            self.adapter.add_case_tag(target_cid, "Run_Case_Correlation")
                            exec_record["correlation_tag_triggered"] = True
                        except Exception:
                            pass
                except Exception as exc:
                    exec_record["status"] = "ERROR"
                    exec_record["error"] = str(exc)

                merge_executions.append(exec_record)

        inventory = [
            {
                "case_id": p["case_id"],
                "display_name": p["display_name"],
                "environment": p["environment"],
                "stage": p["stage"],
                "create_time_iso": p["create_time_iso"],
                "alert_count": p["alert_count"],
                "tags": p["tags"],
                "high_signal_entities": p["entities"],
            }
            for p in profiles
        ]

        result = CaseGroupingResult(
            dry_run=dry_run,
            environment_filter=env_filter_clean,
            lookback_hours=lookback_hours,
            grouping_window_hours=grouping_window_hours,
            min_shared_entities=min_shared_entities,
            max_distinct_hosts_per_case=max_distinct_hosts_per_case,
            min_case_age_minutes=min_case_age_minutes,
            scanned_cases_count=len(profiles),
            eligible_cases_count=len(eligible_profiles),
            skipped_multi_host_cases=skipped_multi_host,
            skipped_settling_cases=skipped_settling,
            overlap_pairs_count=len(overlap_pairs),
            overlap_pairs=overlap_pairs,
            merge_clusters_count=len(merge_clusters),
            merge_clusters=merge_clusters,
            merge_executions=merge_executions,
            case_entity_inventory=inventory,
        )
        result.summary_markdown = self._build_summary_markdown(result)
        return result

    def _build_cluster_wall_comment(self, cl: Dict[str, Any]) -> str:
        target_cid = cl["target_case_id"]
        sources = cl["source_cases"]
        shared = cl["shared_entities"]
        lines = [
            "### 🔗 Automated High-Signal Case Grouping & Merge",
            f"- **Target Surviving Case:** `#{target_cid}` ({cl['target_case_title']})",
            f"- **Environment:** `{cl['environment']}`",
            "- **Merged Child Cases:**",
        ]
        for sc in sources:
            lines.append(
                f"  - `#{sc['case_id']}` — **{sc['display_name']}** "
                f"(`{sc['alert_count']}` alert(s), created `{sc.get('create_time_iso') or 'N/A'}`)"
            )
        lines.append("- **Shared High-Signal Entities:**")
        for etype, vals in shared.items():
            lines.append(f"  - `{etype}`: {', '.join(f'`{v}`' for v in vals)}")
        return "\n".join(lines)

    def _build_summary_markdown(self, res: CaseGroupingResult) -> str:
        mode_str = "DRY RUN (No Cases Modified)" if res.dry_run else "LIVE MERGE EXECUTION"
        env_str = ", ".join(res.environment_filter) if res.environment_filter else "ALL Environments"
        lines = [
            f"## 🛡️ SOAR High-Signal Case Grouping Report — {mode_str}",
            f"- **Environment Scope:** `{env_str}`",
            f"- **Lookback / Grouping Window:** `{res.lookback_hours}h` lookback | `{res.grouping_window_hours}h` grouping window",
            f"- **Cases Scanned:** `{res.scanned_cases_count}` (`{res.eligible_cases_count}` eligible, `{len(res.skipped_multi_host_cases)}` multi-host magnets skipped)",
            f"- **Proposed Merge Clusters:** `{res.merge_clusters_count}` (from `{res.overlap_pairs_count}` overlapping pairs)",
            "",
        ]
        if res.merge_clusters:
            lines.append("### 🔗 Identified Merge Clusters")
            lines.append("| Target Case | Source Cases to Merge | Shared High-Signal Entities | Status |")
            lines.append("| :--- | :--- | :--- | :--- |")
            exec_by_target = {e["target_case_id"]: e for e in res.merge_executions}
            for cl in res.merge_clusters:
                tcid = cl["target_case_id"]
                t_label = f"**#{tcid}** ({cl['target_case_title']})"
                s_label = ", ".join(
                    f"**#{sc['case_id']}** ({sc['display_name']})" for sc in cl["source_cases"]
                )
                ent_parts = []
                for et, vals in cl["shared_entities"].items():
                    ent_parts.append(f"{et}: {', '.join(f'`{v}`' for v in vals)}")
                ent_str = "<br>".join(ent_parts)
                st = "DRY_RUN_READY" if res.dry_run else exec_by_target.get(tcid, {}).get("status", "UNKNOWN")
                lines.append(f"| {t_label} | {s_label} | {ent_str} | `{st}` |")
            lines.append("")

        if res.skipped_multi_host_cases:
            lines.append("### ⚠️ Skipped Multi-Host Magnet Cases (Guardrail Triggered)")
            for mh in res.skipped_multi_host_cases:
                lines.append(
                    f"- **Case #{mh['case_id']} ({mh['display_name']})**: `{mh['alert_count']}` alerts across "
                    f"`{mh['distinct_hostnames_count']}` distinct hosts ({', '.join(f'`{h}`' for h in mh['hostnames'])})"
                )
            lines.append("")

        return "\n".join(lines)
